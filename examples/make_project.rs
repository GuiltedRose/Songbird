//! Generate an original audio fixture project. This never simulates a microphone take.
use anyhow::{Result, ensure};
use songbird::{
    codec::Encoder,
    gui,
    project::Project,
    voice::{Bank, Phoneme},
};
use std::{
    collections::BTreeMap,
    f64::consts::{PI, TAU},
    path::PathBuf,
};
fn main() -> Result<()> {
    let args = std::env::args().skip(1).collect::<Vec<_>>();
    let root = PathBuf::from(
        args.first()
            .map(String::as_str)
            .unwrap_or("songbird-example"),
    );
    ensure!(!root.exists(), "example destination must not exist");
    let mut p = Project::create(&root, gui::DEFAULT.into())?;
    let rate = 48000;
    let mut bell = Encoder::create(&p.root.join("samples/bell.flac"), rate, 2, 24)?;
    let mut texture = Encoder::create(&p.root.join("samples/texture.wav"), rate, 1, 24)?;
    for block in 0..94 {
        let mut b = vec![];
        let mut t = vec![];
        for i in 0..1024 {
            let time = (block * 1024 + i) as f64 / rate as f64;
            if time >= 2. {
                break;
            }
            let value = ((TAU * 440. * time).sin() * 0.16 + (TAU * 1103. * time).sin() * 0.06)
                * (-time * 3.).exp();
            b.push([value as f32; 2]);
            let value = ((TAU * 130.81 * time).sin() + (TAU * 196. * time).sin())
                * 0.055
                * (PI * time / 2.).sin();
            t.push([value as f32; 2]);
        }
        bell.write(&b)?;
        texture.write(&t)?;
    }
    bell.finish()?;
    texture.finish()?;
    std::fs::create_dir_all(p.root.join("voices/analytic/samples"))?;
    let path = p.root.join("voices/analytic/samples/aa.wav");
    let mut e = Encoder::create(&path, rate, 1, 24)?;
    let mut data = vec![];
    for i in 0..24000 {
        let time = i as f64 / rate as f64;
        let mut value = 0.;
        for harmonic in 1..=60 {
            let f = 220. * harmonic as f64;
            let formant = |center: f64, width: f64| (-0.5 * ((f - center) / width).powi(2)).exp();
            let amp =
                (formant(730., 90.) + 0.5 * formant(1090., 110.) + 0.25 * formant(2440., 180.))
                    / (harmonic as f64).sqrt();
            value += amp * (TAU * f * time).sin();
        }
        data.push([(value * 0.13) as f32; 2]);
    }
    e.write(&data)?;
    e.finish()?;
    let bank = Bank {
        version: 1,
        name: "Analytic AA; original generated vowel, not a recorded person".into(),
        license: "CC0-1.0; generated by examples/make_project.rs".into(),
        samples: vec![Phoneme {
            phoneme: "AA".into(),
            file: "samples/aa.wav".into(),
            root: 220.,
            low: 45,
            high: 76,
            onset: 0.,
            sustain: 0.04,
            release: None,
            end: 0.46,
            voiced: true,
            style: "normal".into(),
            register: "alto".into(),
            gain: 1.,
        }],
        dictionary: BTreeMap::from([("AH".into(), "AA".into())]),
        language: None,
        inventory: None,
        provider: None,
        generation: None,
    };
    std::fs::write(
        p.root.join("voices/analytic/voicebank.toml"),
        toml::to_string_pretty(&bank)?,
    )?;
    p.source.push_str("\nvoice Analytic { language english; bank voices/analytic; register alto }\ntrack singer { use voice Analytic; lyrics \"ah ~ ah ~\"; notes \"C4:2 E4:2 G4:2 E4:2\"; at 8b; vibrato 0.2; breathiness 0.05; gain -7db; reverb 0.15 }\ntrack bell {import samples/bell.flac; at 4b; gain -6db; pan -0.25; delay 0.22 0.3 0.2}\ntrack texture {import samples/texture.wav; trim 0.1 1.8; reverse; fade in 80ms; fade out 200ms; place at 8b; duplicate 16b; pitch 3; gain -9db; pan 0.35}\n");
    if let Some(take) = args.get(1) {
        let asset = p.import(&PathBuf::from(take))?;
        p.source.push_str(&format!("\ntrack recorded_voiceover {{import \"{asset}\";at 2b;gain -3db;compress -16 3;fade in 20ms;fade out 50ms}}\n"));
    }
    p.save()?;
    println!(
        "Created {}. Analytic AA demonstrates the sample engine; it does not establish English singing intelligibility. No hardware recording is claimed.",
        p.root.display()
    );
    Ok(())
}
